// Builds src/lib/sky/data.ts from Olaf Frohn's d3-celestial data (BSD 3-Clause):
// stars down to magnitude 4.6, every constellation's line figure, and its name.
//
//   mkdir -p /tmp/celestial && cd /tmp/celestial
//   for f in stars.6.json constellations.lines.json constellations.json starnames.json; do
//     curl -fLO https://cdn.jsdelivr.net/npm/d3-celestial@0.7.35/data/$f; done
//   node scripts/build-sky-data.mjs /tmp/celestial

import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/build-sky-data.mjs <folder with the d3-celestial json files>");
  process.exit(1);
}
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));

const MAG_LIMIT = 4.6;
const r2 = (x) => Math.round(x * 100) / 100;
// d3-celestial stores right ascension as -180..180 degrees; keep 0..360
const ra = (x) => r2(((x % 360) + 360) % 360);

const names = read("starnames.json");
const stars = read("stars.6.json")
  .features.filter((f) => f.properties.mag <= MAG_LIMIT)
  .sort((a, b) => a.properties.mag - b.properties.mag)
  .map((f) => {
    const [x, y] = f.geometry.coordinates;
    const name = names[f.id]?.name || "";
    // Only the brightest get a label, so the map stays readable
    return f.properties.mag <= 1.5 && name ? [ra(x), r2(y), r2(f.properties.mag), name] : [ra(x), r2(y), r2(f.properties.mag)];
  });

const lines = read("constellations.lines.json").features.map((f) => [
  f.id,
  f.geometry.coordinates.map((line) => line.map(([x, y]) => [ra(x), r2(y)])),
]);

const labels = read("constellations.json").features.map((f) => {
  const [x, y] = f.geometry.coordinates;
  return [f.id, f.properties.en ?? f.properties.name, f.properties.hi ?? "", ra(x), r2(y)];
});

const out = `// Generated by scripts/build-sky-data.mjs. Do not edit.
// Star positions and constellation figures from d3-celestial by Olaf Frohn,
// https://github.com/ofrohn/d3-celestial, BSD 3-Clause License, Copyright (c) 2015 Olaf Frohn.
// Coordinates are J2000 right ascension and declination in degrees.

/** [ra, dec, magnitude, name?], brightest first */
export const STARS: [number, number, number, string?][] = ${JSON.stringify(stars)};

/** [id, polylines of [ra, dec]] */
export const LINES: [string, [number, number][][]][] = ${JSON.stringify(lines)};

/** [id, English name, Hindi name, ra, dec] */
export const LABELS: [string, string, string, number, number][] = ${JSON.stringify(labels)};
`;
fs.mkdirSync("src/lib/sky", { recursive: true });
fs.writeFileSync("src/lib/sky/data.ts", out);
console.log(`${stars.length} stars, ${lines.length} figures, ${labels.length} labels, ${(out.length / 1024).toFixed(0)} KB`);
